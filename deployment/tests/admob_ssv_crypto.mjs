import assert from 'node:assert/strict';
import {generateKeyPairSync, sign} from 'node:crypto';
import {verifyCallback} from '../../supabase/functions/admob-ssv/verify.mjs';
const {privateKey,publicKey}=generateKeyPairSync('ec',{namedCurve:'prime256v1'});
const keys=new Map([['123',publicKey.export({type:'spki',format:'pem'})]]);
const id='11111111-1111-1111-1111-111111111111';
const content=`ad_network=5450213213286189855&ad_unit=7155046146&custom_data=${id}&reward_amount=1&reward_item=bisca_reward&timestamp=${Date.now()}&transaction_id=abc123&user_id=${id}`;
const signed=c=>'https://example.com/ssv?'+c+'&signature='+sign('sha256',Buffer.from(c),privateKey).toString('base64url')+'&key_id=123';
assert.equal(verifyCallback(signed(content),keys).p_session,id);
assert.equal(verifyCallback(signed(content.replace('7155046146','ca-app-pub-4798197645196973%2F7977173220')),keys).p_unit,'7977173220');
for(const c of [content.replace('reward_amount=1','reward_amount=5000'),content.replace('7155046146','999'),content+'&user_id='+id,content.replace('bisca_reward','coins'),content.replace(`custom_data=${id}`,'custom_data=invalid')]) assert.throws(()=>verifyCallback(signed(c),keys));
assert.throws(()=>verifyCallback(signed(content).replace('abc123','abc124'),keys));
assert.throws(()=>verifyCallback(signed(content)+'&extra=1',keys));
assert.throws(()=>verifyCallback(signed(content),new Map()));
const probe=content.replace(`&custom_data=${id}`,'').replace(`&user_id=${id}`,'');
assert.equal(verifyCallback(signed(probe),keys),null,'Signed console probe must never produce a reward payload');
assert.equal(verifyCallback(signed(probe+'&user_id=&custom_data='),keys),null);
assert.throws(()=>verifyCallback(signed(probe).replace('abc123','tampered'),keys));
assert.throws(()=>verifyCallback(signed(probe+'&user_id='+id),keys),'Partial identities must still be rejected');
console.log('PASS: Google-style DER/ECDSA signature, encoded payload, units, duplicate fields, tampering');
